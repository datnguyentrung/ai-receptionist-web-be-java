create table training.face_check_in_scan (
    request_id uuid primary key,
    device_id varchar(128) not null,
    user_id uuid not null,
    upload_ticket_hash varchar(64) not null,
    ticket_used_at timestamptz,
    stage varchar(32) not null,
    expires_at timestamptz not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    version bigint not null default 0
);

create table training.face_check_in_event (
    event_id bigint generated by default as identity primary key,
    request_id uuid not null references training.face_check_in_scan(request_id) on delete cascade,
    stage varchar(32) not null,
    result_payload text,
    error_code varchar(128),
    error_title varchar(255),
    error_detail text,
    occurred_at timestamptz not null,
    constraint uk_face_check_in_event_request_stage unique (request_id, stage)
);

create index idx_face_check_in_scan_expiry on training.face_check_in_scan (expires_at, stage);
create index idx_face_check_in_event_replay on training.face_check_in_event (request_id, event_id);
